#ifndef __SOC_MEDIATEK_MT6878_MMSYS_H
#define __SOC_MEDIATEK_MT6878_MMSYS_H

/*
 * MT6878 display crossbar. The OVLs feed "blend"/"background" crossbars,
 * the PQ engines are chained through per-engine SEL_IN/SOUT_SEL muxes, and
 * the PQ output reaches DSC/DSI through split-out and comp-out crossbars.
 *
 * The main path routes OVL0_2L -> BLEND_CB0 -> PQ0_IN_CB -> RSZ0 -> TDSHP0
 * -> COLOR0 -> CCORR0 -> CCORR1 -> AAL0 -> GAMMA0 -> POSTMASK0 -> DITHER0 ->
 * PQ0_OUT_CB -> SPLIT_OUT_CB2 -> DSC0 -> COMP0_OUT_CB -> DSI0. RSZ0 -> TDSHP0,
 * CCORR0 -> CCORR1 and GAMMA0 -> POSTMASK0 are hard-wired; C3D0 is bypassed.
 */
#define MT6878_MMSYS_OVL_CON			0xc08
#define MT6878_OVL0_2L_TO_BLEND_CB0		BIT(2)
#define MT6878_OVL0_2L_TO_BG_CB0		BIT(3)
#define MT6878_OVL_BG_CB0_MOUT_EN		0xc10
#define MT6878_OVL_BLEND_CB0_MOUT_EN		0xc34
#define MT6878_OVL_BLEND_CB2_MOUT_EN		0xc3c
#define MT6878_BLEND_CB_TO_PQ0_IN_CB		BIT(0)
#define MT6878_PQ_IN_CB0_MOUT_EN		0xd00
#define MT6878_PQ0_IN_CB_TO_RSZ0		BIT(0)
#define MT6878_PQ_OUT_CB0_MOUT_EN		0xd20
#define MT6878_PQ0_OUT_CB_TO_SPLIT_OUT_CB2	BIT(1)
#define MT6878_SPLIT_OUT_CB2_MOUT_EN		0xd54
#define MT6878_SPLIT_OUT_CB_TO_DSC0_0		BIT(0)
#define MT6878_SPLIT_OUT_CB0_SEL_IN		0xd60
#define MT6878_SPLIT_OUT_CB_FROM_MOUT_CB2	0x2
#define MT6878_COMP_OUT_CB0_MOUT_EN		0xd74
#define MT6878_COMP0_OUT_CB_TO_DSI0		BIT(0)

#define MT6878_DISP_AAL0_SOUT_SEL		0xe00
#define MT6878_AAL0_SOUT_TO_GAMMA0		0x3
#define MT6878_DISP_CCORR0_SEL_IN		0xe0c
#define MT6878_CCORR0_SEL_IN_FROM_COLOR0	0x0
#define MT6878_DISP_CCORR1_SOUT_SEL		0xe10
#define MT6878_CCORR1_SOUT_TO_AAL0		0x2
#define MT6878_DISP_COLOR0_SEL_IN		0xe14
#define MT6878_COLOR0_SEL_IN_FROM_TDSHP0	0x1
#define MT6878_DISP_COLOR0_SOUT_SEL		0xe18
#define MT6878_COLOR0_SOUT_TO_CCORR0		0x0
#define MT6878_DISP_GAMMA0_SEL_IN		0xe1c
#define MT6878_GAMMA0_SEL_IN_FROM_AAL0		0x2
#define MT6878_DISP_AAL0_SEL_IN			0xe20
#define MT6878_AAL0_SEL_IN_FROM_CCORR1		0x1
#define MT6878_DISP_POSTMASK0_SOUT_SEL		0xe24
#define MT6878_POSTMASK0_SOUT_TO_DITHER0	0x0
#define MT6878_DISP_TDSHP0_SOUT_SEL		0xe28
#define MT6878_TDSHP0_SOUT_TO_COLOR0		0x1

#define MT6878_MOUT_MASK			GENMASK(4, 0)
#define MT6878_SEL_MASK				GENMASK(2, 0)
#define MT6878_ALL_MASK				GENMASK(15, 0)

static const struct mtk_mmsys_routes mt6878_mmsys_routing_table[] = {
	/* OVL0_2L -> BLEND_CB0 (not BG_CB0) -> PQ0_IN_CB -> RSZ0 */
	MMSYS_ROUTE(OVL_2L0, RSZ0,
		    MT6878_MMSYS_OVL_CON,
		    MT6878_OVL0_2L_TO_BLEND_CB0 | MT6878_OVL0_2L_TO_BG_CB0,
		    MT6878_OVL0_2L_TO_BLEND_CB0),
	MMSYS_ROUTE(OVL_2L0, RSZ0,
		    MT6878_OVL_BG_CB0_MOUT_EN, MT6878_ALL_MASK, 0),
	MMSYS_ROUTE(OVL_2L0, RSZ0,
		    MT6878_OVL_BLEND_CB0_MOUT_EN, MT6878_ALL_MASK,
		    MT6878_BLEND_CB_TO_PQ0_IN_CB),
	/* the bootloader chains OVL2_2L into PQ0_IN_CB as well; detach it */
	MMSYS_ROUTE(OVL_2L0, RSZ0,
		    MT6878_OVL_BLEND_CB2_MOUT_EN, MT6878_ALL_MASK, 0),
	MMSYS_ROUTE(OVL_2L0, RSZ0,
		    MT6878_PQ_IN_CB0_MOUT_EN, MT6878_MOUT_MASK,
		    MT6878_PQ0_IN_CB_TO_RSZ0),
	/* RSZ0 -> TDSHP0 is hard-wired; TDSHP0 -> COLOR0 */
	MMSYS_ROUTE(TDSHP0, COLOR0,
		    MT6878_DISP_TDSHP0_SOUT_SEL, MT6878_SEL_MASK,
		    MT6878_TDSHP0_SOUT_TO_COLOR0),
	MMSYS_ROUTE(TDSHP0, COLOR0,
		    MT6878_DISP_COLOR0_SEL_IN, MT6878_SEL_MASK,
		    MT6878_COLOR0_SEL_IN_FROM_TDSHP0),
	/* COLOR0 -> CCORR0 */
	MMSYS_ROUTE(COLOR0, CCORR,
		    MT6878_DISP_COLOR0_SOUT_SEL, MT6878_SEL_MASK,
		    MT6878_COLOR0_SOUT_TO_CCORR0),
	MMSYS_ROUTE(COLOR0, CCORR,
		    MT6878_DISP_CCORR0_SEL_IN, MT6878_SEL_MASK,
		    MT6878_CCORR0_SEL_IN_FROM_COLOR0),
	/* CCORR0 -> CCORR1 is hard-wired; CCORR1 -> AAL0, bypassing C3D0 */
	MMSYS_ROUTE(CCORR1, AAL0,
		    MT6878_DISP_CCORR1_SOUT_SEL, MT6878_SEL_MASK,
		    MT6878_CCORR1_SOUT_TO_AAL0),
	MMSYS_ROUTE(CCORR1, AAL0,
		    MT6878_DISP_AAL0_SEL_IN, MT6878_SEL_MASK,
		    MT6878_AAL0_SEL_IN_FROM_CCORR1),
	/* AAL0 -> GAMMA0 */
	MMSYS_ROUTE(AAL0, GAMMA,
		    MT6878_DISP_AAL0_SOUT_SEL, MT6878_SEL_MASK,
		    MT6878_AAL0_SOUT_TO_GAMMA0),
	MMSYS_ROUTE(AAL0, GAMMA,
		    MT6878_DISP_GAMMA0_SEL_IN, MT6878_SEL_MASK,
		    MT6878_GAMMA0_SEL_IN_FROM_AAL0),
	/* GAMMA0 -> POSTMASK0 is hard-wired; POSTMASK0 -> DITHER0 */
	MMSYS_ROUTE(POSTMASK0, DITHER0,
		    MT6878_DISP_POSTMASK0_SOUT_SEL, MT6878_SEL_MASK,
		    MT6878_POSTMASK0_SOUT_TO_DITHER0),
	/* DITHER0 -> PQ0_OUT_CB -> SPLIT_OUT_CB2 -> DSC0 */
	MMSYS_ROUTE(DITHER0, DSC0,
		    MT6878_PQ_OUT_CB0_MOUT_EN, MT6878_MOUT_MASK,
		    MT6878_PQ0_OUT_CB_TO_SPLIT_OUT_CB2),
	MMSYS_ROUTE(DITHER0, DSC0,
		    MT6878_SPLIT_OUT_CB2_MOUT_EN, MT6878_MOUT_MASK,
		    MT6878_SPLIT_OUT_CB_TO_DSC0_0),
	MMSYS_ROUTE(DITHER0, DSC0,
		    MT6878_SPLIT_OUT_CB0_SEL_IN, MT6878_SEL_MASK,
		    MT6878_SPLIT_OUT_CB_FROM_MOUT_CB2),
	/* DSC0 -> COMP0_OUT_CB -> DSI0 */
	MMSYS_ROUTE(DSC0, DSI0,
		    MT6878_COMP_OUT_CB0_MOUT_EN, MT6878_MOUT_MASK,
		    MT6878_COMP0_OUT_CB_TO_DSI0),
};

#endif /* __SOC_MEDIATEK_MT6878_MMSYS_H */
